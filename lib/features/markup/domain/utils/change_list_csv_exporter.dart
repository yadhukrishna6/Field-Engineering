import 'package:intl/intl.dart';
import '../models/drawing_file.dart';
import '../models/field_change_item.dart';

class ChangeListCsvExporter {
  /// Generates a RFC-4180 compliant CSV string for CAD drafters and office engineers.
  static String generateCsv({
    required DrawingFile drawing,
    required List<FieldChangeItem> changes,
  }) {
    final buffer = StringBuffer();

    // CSV Header
    buffer.writeln('Item_No,Change_Type,Drawing_No,Revision,Page_No,Attached_Tag,Description,Author,Timestamp,Latitude,Longitude,Status');

    for (final change in changes) {
      final dateStr = DateFormat('yyyy-MM-dd HH:mm:ss').format(change.timestamp);
      final latStr = change.gps?.lat.toStringAsFixed(6) ?? '';
      final lngStr = change.gps?.lng.toStringAsFixed(6) ?? '';

      final row = [
        change.itemNumber.toString(),
        _escapeCsv(change.changeType),
        _escapeCsv(drawing.drawingNumber ?? drawing.name),
        _escapeCsv(drawing.revision ?? 'REV 0'),
        change.pageNumber.toString(),
        _escapeCsv(change.attachedTag ?? 'N/A'),
        _escapeCsv(change.description),
        _escapeCsv(change.author),
        dateStr,
        latStr,
        lngStr,
        _escapeCsv(change.status),
      ];

      buffer.writeln(row.join(','));
    }

    return buffer.toString();
  }

  /// Generates an executive Markdown summary report for 1-tap clipboard sharing.
  static String generateSummaryMarkdown({
    required DrawingFile drawing,
    required List<FieldChangeItem> changes,
  }) {
    final buffer = StringBuffer();
    final nowStr = DateFormat('yyyy-MM-dd HH:mm').format(DateTime.now());

    buffer.writeln('# FIELD REDLINE & CHANGE SUMMARY');
    buffer.writeln('**Drawing:** ${drawing.drawingNumber ?? drawing.name} (${drawing.revision ?? "REV 0"})');
    buffer.writeln('**Job:** ${drawing.jobNumber ?? "JOB-4500-DESERT"} | **Project:** ${drawing.projectName ?? "Desert Facility"}');
    buffer.writeln('**Export Date:** $nowStr | **Total Action Items:** ${changes.length}\n');

    buffer.writeln('| # | Type | Attached Tag | Field Directive / Note | Author | GPS |');
    buffer.writeln('|---|---|---|---|---|---|');

    for (final c in changes) {
      final gpsStr = c.gps != null ? '${c.gps!.lat.toStringAsFixed(4)}°, ${c.gps!.lng.toStringAsFixed(4)}°' : '-';
      final tagStr = c.attachedTag ?? '-';
      buffer.writeln('| #${c.itemNumber} | **${c.changeType}** | `$tagStr` | ${c.description} | ${c.author} | $gpsStr |');
    }

    buffer.writeln('\n*Generated by Field Engineering Drawing Markup App*');
    return buffer.toString();
  }

  static String _escapeCsv(String field) {
    if (field.contains(',') || field.contains('"') || field.contains('\n') || field.contains('\r')) {
      return '"${field.replaceAll('"', '""')}"';
    }
    return field;
  }
}
